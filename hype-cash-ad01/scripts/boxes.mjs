// Records element boxes (CSS px) on the real pages, so callouts in the ad point at real UI positions.
import { chromium } from "playwright-core";
import { writeFileSync } from "node:fs";
import { executablePath } from "./chrome.mjs";
const BASE = process.argv[2] || "http://localhost:3123";
const browser = await chromium.launch({ executablePath });
const ctx = await browser.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
await page.goto(`${BASE}/playbook`);
await page.evaluate((pw) => localStorage.setItem("hypecash_access", pw), process.env.GATE_PASSWORD);
const out = {};
const grab = async (key, sel) => { out[key] = await page.$$eval(sel, (els) => els.map((e) => { const r = e.getBoundingClientRect(); return { text: e.innerText.slice(0, 40).replace(/\n/g, " | "), x: r.x, y: r.y + scrollY, w: r.width, h: r.height }; })); };
await page.goto(`${BASE}/playbook/missoes`, { waitUntil: "networkidle" });
await grab("map_cards", "main a[href^='/playbook/missao/']");
await grab("map_progress", "main section");
await page.goto(`${BASE}/playbook/missao/entre-no-jogo`, { waitUntil: "networkidle" });
await grab("m1_sections", "main section, main h2");
await page.goto(`${BASE}/playbook/ferramentas`, { waitUntil: "networkidle" });
await grab("tools_sections", "main h2, main h3");
writeFileSync(new URL("../assets/captures/boxes.json", import.meta.url), JSON.stringify(out, null, 1));
console.log(JSON.stringify(out));
await browser.close();
